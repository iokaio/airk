//! Literal final-plan defaults and an additive native fixture; historical cases stay explicit.
use super::Budget;
use anyhow::Result;
use serde_json::json;

fn historical_budget() -> Budget {
    Budget {
        calls: 8,
        rounds: 3,
        fanout: 8,
        input_tokens: 2048,
        candidates: 32,
        max_bytes: 262_144,
        deadline_ms: 30_000,
    }
}

#[test]
fn shipping_default_is_literal_8192_shared_tokens_and_120000_ms() -> Result<()> {
    let budget = Budget::default();
    budget.validate()?;
    assert_eq!(
        serde_json::to_value(&budget)?,
        json!({
            "calls":8,"rounds":3,"fanout":8,"input_tokens":8192,
            "candidates":32,"max_bytes":262144,"deadline_ms":120000
        })
    );
    Ok(())
}

#[test]
fn historical_control_remains_explicit_and_byte_identical() -> Result<()> {
    let historical = historical_budget();
    historical.validate()?;
    assert_eq!(
        serde_json::to_string(&historical)?,
        r#"{"calls":8,"rounds":3,"fanout":8,"input_tokens":2048,"candidates":32,"max_bytes":262144,"deadline_ms":30000}"#
    );
    Ok(())
}

#[test]
fn default_budget_native_fixture_emitter() -> Result<()> {
    let default = Budget::default();
    assert_eq!(default.input_tokens, 8192);
    assert_eq!(default.deadline_ms, 120_000);
    default.validate()?;
    let historical = historical_budget();
    let mut cases = Vec::new();
    for (id, input_tokens, deadline_ms, accepted) in [
        ("new_maximum", 8192, 120_000, true),
        ("token_overflow", 8193, 120_000, false),
        ("deadline_overflow", 8192, 120_001, false),
        ("zero_tokens", 0, 120_000, false),
        ("zero_deadline", 8192, 0, false),
        ("historical_control", 2048, 30_000, true),
    ] {
        let budget = Budget {
            input_tokens,
            deadline_ms,
            ..default.clone()
        };
        assert_eq!(budget.validate().is_ok(), accepted, "{id}");
        cases.push(json!({"id":id,"budget":budget,"accepted":accepted}));
    }
    assert_eq!(crate::read_attempt::MAX_READ_BUDGET.as_millis(), 125_000);
    let document = json!({
        "schema":"airk.arbiter.budget-cases/1",
        "qualification":false,
        "default_budget":default,
        "historical_control":historical,
        "operation_deadline_ms":120000,
        "transport_overhead_ms":5000,
        "transport_deadline_ms":125000,
        "selected_focus_pair_tokens":512,
        "cases":cases
    });
    let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    if let Some(path) = std::env::var_os("AIRK_WRITE_ARBITER_BUDGET_CASES") {
        let mut bytes = serde_json::to_vec_pretty(&document)?;
        bytes.push(b'\n');
        std::fs::write(path, bytes)?;
    } else {
        let path = manifest.join("../../fixtures/split/arbiter/budget_cases.json");
        let retained: serde_json::Value = serde_json::from_slice(&std::fs::read(path)?)?;
        assert_eq!(document, retained, "regenerate budget cases only from Core");
    }
    // Runtime constants are emitted directly by the native owner. The general
    // JSON-schema type pilot remains declaration-only and does not mirror them.
    let typescript = format!(
        "// SPDX-License-Identifier: Apache-2.0\n\
         // Generated by airk-core arbiter::budget_tests::default_budget_native_fixture_emitter. Do not edit.\n\
         export const DEFAULT_CONTEXT_BUDGET = {} as const;\n\
         export const READ_OPERATION_DEADLINE_MS = {};\n\
         export const READ_TRANSPORT_OVERHEAD_MS = 5000;\n\
         export const READ_TRANSPORT_DEADLINE_MS = {};\n",
        serde_json::to_string(&default)?,
        default.deadline_ms,
        crate::read_attempt::MAX_READ_BUDGET.as_millis(),
    );
    if let Some(path) = std::env::var_os("AIRK_WRITE_ARBITER_BUDGET_TYPESCRIPT") {
        std::fs::write(path, typescript.as_bytes())?;
    } else {
        let path = manifest.join("../../packages/vscode/src/generated/arbiterBudget.ts");
        assert_eq!(
            std::fs::read(path)?,
            typescript.as_bytes(),
            "regenerate runtime budget constants only from Core"
        );
    }
    Ok(())
}
