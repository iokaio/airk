def marker(raw):
    text=raw.decode('utf-8-sig',errors='strict').replace('\r\n','\n')
    for prefix,role in [
        ('# CMAKE generated file: DO NOT EDIT!','cmake_generated_file'),
        ('# CMake generated Testfile for ','cmake_testfile'),
        ('/* generated by CMake */','cmake_precompiled_header'),
        ('// Generated by the protocol buffer compiler.','protobuf_generated_source'),
    ]:
        if text.startswith(prefix):return role
    if text.startswith('# Install script for directory: ') and '\n# Set the install prefix' in text:return 'cmake_install_script'
    return None

def template_match(raw,template):
    a=raw.decode('utf-8-sig').replace('\r\n','\n');b=template.decode('utf-8-sig').replace('\r\n','\n')
    chunks=re.split(r'(@[A-Za-z_][A-Za-z0-9_]*@)',b)
    if len(chunks)<3:return False
    literals=chunks[::2]
    if len(literals)>256 or len(a)>1<<20 or len(b)>1<<20:raise ValueError('template role bound exceeded')
    if not a.startswith(literals[0]):return False
    cursor=len(literals[0])
    for literal in literals[1:-1]:
        found=a.find(literal,cursor)
        if found<0:return False
        cursor=found+len(literal)
    return a.endswith(literals[-1]) and len(a)-len(literals[-1])>=cursor

def relative(path):
    return Path(path).resolve().relative_to(owner.ROOT).as_posix()

def configure_root(argv):
    if not isinstance(argv,list) or '-B' not in argv:return None
    i=argv.index('-B')
    if i+1==len(argv):raise ValueError('missing configure output')
    return Path(argv[i+1]).resolve()

def context(path,cache):
    parts=path.split('/');prefix='/'.join(parts[:3])
    if prefix.startswith('artifacts/advanced-split/ort130-x64'):
        receipt=prefix+('/tools/attempt.json' if '/tools/ninja-build/' in path else '/build-receipt.json')
    elif prefix.startswith('artifacts/advanced-split/msvc-configure-'):receipt=prefix+'/receipt.json'
    elif path.startswith(owner.OLD+'/b/'):receipt=owner.OLD+'/windows-static-build-result.json'
    else:return None
    if receipt in cache:return cache[receipt]
    try:
        data,pin=owner.document(receipt);argv=data.get('configure_argv',data.get('configure'));output=configure_root(argv)
        if output is None:return None
        relative(output)
        cmake=data.get('toolchain',{}).get('cmake',data.get('cmake'))
        evidence=[pin]
        if not cmake:
            executable=Path(argv[0]);attempt=executable.parents[2]/'attempt.json'
            if attempt.is_file():
                tools,tool_pin=owner.document(relative(attempt));evidence.append(tool_pin);cmake=tools.get('cmake')
        if not cmake:cmake={'path':argv[0],'identity_from_receipt_only':True}
        if Path(cmake['path']).resolve()!=Path(argv[0]).resolve():raise ValueError('generator path differs from command')
        share=Path(cmake['path']).parents[1]/'share';modules=[]
        if share.is_dir():modules=[p/'Modules' for p in share.iterdir() if p.name.startswith('cmake-') and (p/'Modules').is_dir()]
        result={'root':output,'receipt':pin,'argv':argv,'generator':cmake,'evidence':evidence,'modules':modules}
    except (OSError,ValueError,KeyError) as exc:result={'error':str(exc),'receipt_path':receipt}
    cache[receipt]=result;return result

def project(platform,component):
    sources=[];pins=[]
    for path,sha,key in [(platform[0],platform[1],'remaining'),(component[0],component[1],'unresolved')]:
        data,pin=owner.document(path,sha);pins.append(pin)
        sources.extend(r for r in data[key] if key!='remaining' or r.get('lane')=='platform_inventory')
    result=[];unresolved=[];cache={};seen=set()
    for row in sources:
        path=row['path']
        if path in seen:raise ValueError('duplicate role candidate')
        seen.add(path);ctx=context(path,cache)
        if not ctx or 'error' in ctx:
            unresolved.append({**row,'role_reason':ctx.get('error') if ctx else 'No reviewed CMake command context'});continue
        source=owner.input_path(path)
        if not source.is_relative_to(ctx['root']):
            unresolved.append({**row,'role_reason':'Outside recorded configure -B output root'});continue
        if row['bytes']>1<<20:
            unresolved.append({**row,'role_reason':'Role inspection size bound'});continue
        raw,pin=owner.authenticated_bytes(path,row['source_sha256'])
        if pin['bytes']!=row['bytes']:raise ValueError('candidate size changed')
        try:role=marker(raw)
        except UnicodeError:role=None
        evidence=list(ctx['evidence']);method='explicit producer marker under recorded configure output'
        if not role and len(ctx['modules'])==1 and source.name in {'CMakeASMCompiler.cmake','CMakeASM_MASMCompiler.cmake','CMakeCCompiler.cmake','CMakeCXXCompiler.cmake','CMakeRCCompiler.cmake','CMakeSystem.cmake','CMakeCCompilerId.c','CMakeCXXCompilerId.cpp'}:
            template=ctx['modules'][0]/(source.name+'.in')
            if template.is_file():
                try:
                    body,tpin=owner.authenticated_bytes(relative(template))
                    if template_match(raw,body):role='cmake_template_output';evidence.append(tpin);method='whole template literal skeleton with named CMake substitutions, CRLF-insensitive role only'
                except (UnicodeError,ValueError):pass
        if not role:
            unresolved.append({**row,'role_reason':'No supported positive marker or full template skeleton'});continue
        result.append({'source':path,'source_sha256':pin['sha256'],'source_bytes':pin['bytes'],'role':'generated_build_output','producer_role':role,'method':method,'configure_output':str(ctx['root']),'configure_argv':ctx['argv'],'generator':ctx['generator'],'evidence':evidence,'exact_historical_bytes_reproduced':False,'whole_directory_exclusion':False})
    for path,pin in dict(owner.CHECKED).items():
        if owner.file_pin(path)!=pin:raise ValueError('role evidence changed')
    return {'schema':'airk.private.generated-build-roles/1','inputs':pins,'code':owner.file_pin('scripts/arbiter/analysis/upstream_ort/generated_roles.py'),'files':result,'unresolved':unresolved,'role_only':True,'qualification':False}

