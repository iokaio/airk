STRING = r'"(?:[^"\\]|\\.)*"'


def rust_strings(value):
    return [json.loads(match) for match in re.findall(STRING, value)]


def context_admitted(name, rules):
    """Model this file's literal/*/** rules, including Docker parent matches.

    Docker's patternmatcher MatchesOrParentMatches applies each ordered pattern
    to the path and every parent, including negations. This intentionally small
    matcher rejects grammar outside the reviewed context policy.
    """
    ignored = False
    parts = name.split("/")
    candidates = ["/".join(parts[:length]) for length in range(1, len(parts) + 1)]
    for line in rules:
        if not line or line.startswith("#"):
            continue
        negated = line.startswith("!")
        pattern = line[1:] if negated else line
        pattern = pattern.rstrip("/")
        if any(char in pattern for char in "?[]\\"):
            raise AssertionError("Unreviewed Docker ignore pattern grammar: " + pattern)
        regex = ""
        offset = 0
        while offset < len(pattern):
            if pattern[offset:offset + 3] == "**/":
                regex += "(?:.*/)?"
                offset += 3
            elif pattern[offset:offset + 2] == "**":
                regex += ".*"
                offset += 2
            elif pattern[offset] == "*":
                regex += "[^/]*"
                offset += 1
            else:
                regex += re.escape(pattern[offset])
                offset += 1
        if any(re.fullmatch(regex, path) for path in candidates):
            ignored = not negated
    return not ignored


def external_rust_inputs(root):
    """Resolve static includes and manifest-relative reads plus the CLI source map."""
    found = set()
    for source in (root / "crates").rglob("*.rs"):
        text = source.read_text(encoding="utf-8")
        crate = root / "crates" / source.relative_to(root / "crates").parts[0]
        paths = []
        for match in re.finditer(r'include(?:_str|_bytes)?!\s*\(\s*(' + STRING + r')\s*,?\s*\)', text):
            paths.append((source.parent, json.loads(match[1])))
        for match in re.finditer(r'concat!\s*\(\s*env!\s*\(\s*"CARGO_MANIFEST_DIR"\s*\)\s*,((?:\s*' + STRING + r'\s*,?)+)\s*\)', text):
            paths.append((crate, "".join(rust_strings(match[1])).lstrip("/")))
        for match in re.finditer(r'Path::new\(\s*env!\(\s*"CARGO_MANIFEST_DIR"\s*\)\s*\)\s*\.join\(([^)]+)\)', text):
            argument = re.fullmatch(r'\s*(' + STRING + r')\s*,?\s*', match[1])
            if argument is None:
                raise AssertionError("Dynamic manifest-relative join needs an explicit inventory: " + str(source))
            paths.append((crate, json.loads(argument[1])))
        for base, name in paths:
            path = (base / name).resolve()
            relative = path.relative_to(root).as_posix()
            if relative in (".", "target/local-vector-model"):
                # Repository-root helpers are resolved by the ELSEWHERE table;
                # onnx.rs's local model directory is generated by provisioning,
                # never admitted as a public source input.
                continue
            if not relative.startswith("crates/"):
                found.add(relative)
    table = (root / "crates/airk-cli/tests/cli_commands.rs").read_text(encoding="utf-8")
    # The pre-split parser-coverage table leaves with the user CLI (split Phase 4).
    table = table.split("const ELSEWHERE:", 1)[1].split("\n];", 1)[0] if "const ELSEWHERE:" in table else ""
    for row in re.finditer(r'\(\s*(' + STRING + r')\s*,\s*(' + STRING + r')\s*,\s*(' + STRING + r')\s*,?\s*\)', table):
        name = json.loads(row[2])
        if name != "this file" and not name.startswith("crates/"):
            found.add(name)
    # Other constructed manifest-root paths in combined_reads.rs point to
    # generated artifacts; common/reviewed.rs obtains the repository root only.
    # Their public CLI source-map reads are represented by ELSEWHERE above.
    # OUT_DIR includes in bundled_assets.rs are generated by build.rs from the
    # separately verified model provisioner, not source inputs. No additional
    # constructed public-file reads are known; add each here when introducing one.
    return found


def relative_frontend_inputs(root):
    """Conservative local import closure, including tsc's erased type inputs.

    Pinned npm dependencies stay owned by package-lock; local TS/JSON/CSS inputs
    must exist and remain under the repository. This is not a JS parser.
    """
    pending = list((root / "packages/admin/src").rglob("*.ts*"))
    found = set()
    pattern = re.compile(r"\b(?:from\s*|import\s*(?:\(\s*)?|require\s*\(\s*)[\"'](\.[^\"']+)[\"']")
    while pending:
        path = pending.pop().resolve()
        if not path.is_relative_to(root.resolve()):
            raise AssertionError("Admin source import escapes the repository")
        name = path.relative_to(root.resolve()).as_posix()
        if name in found:
            continue
        found.add(name)
        if path.suffix not in (".ts", ".tsx", ".mjs", ".js"):
            continue
        for match in pattern.finditer(path.read_text(encoding="utf-8")):
            base = path.parent / match[1]
            candidates = [base, *(Path(str(base) + suffix) for suffix in (".ts", ".tsx", ".json", ".css")), base / "index.ts", base / "index.tsx"]
            resolved = next((candidate for candidate in candidates if candidate.is_file()), None)
            if resolved is None:
                raise AssertionError("Admin local import is missing: " + name + " -> " + match[1])
            pending.append(resolved)
    return found


class ContainerInputInventoryTests(unittest.TestCase):
    def test_static_inference_stage_copies_the_complete_current_producer_helpers(self):
        expected = {'scripts/provision-static-onnx-runtime.py','scripts/static-onnx-runtime-lock.json',
                    'scripts/provision-static-onnx-tools.py','scripts/static-onnx-tools-lock.json',
                    'scripts/provision-static-cmake-source.py','scripts/static-cmake-source-lock.json',
                    'scripts/static-onnx-link-closure.py','scripts/static-onnx-aggregate.py'}
        selected = False
        copied = set()
        for opcode, arguments in BUILD.docker_instructions((ROOT/'Dockerfile').read_text()):
            words = shlex.split(arguments)
            if opcode == 'FROM':
                if selected:break
                selected = words[-2:] == ['AS','static-inference']
            elif selected and opcode == 'COPY':
                copied.update(words[:-1])
        self.assertEqual(copied,expected)

    def test_effective_context_admits_only_manifest_external_files_and_owning_trees(self):
        manifest = json.loads((ROOT / "scripts/container-inputs.json").read_text())
        rules = (ROOT / ".dockerignore").read_text().splitlines()
        self.assertTrue(context_admitted("scripts/neighbor.py", ["**", "!scripts/"]))
        self.assertFalse(context_admitted("scripts/neighbor.py", ["**", "!scripts/", "scripts/**", "!scripts/allowed.py"]))
        for name in manifest["files"]:
            with self.subTest(admitted=name):
                self.assertTrue(context_admitted(name, rules))
        for tree in manifest["trees"]:
            self.assertTrue(context_admitted(tree + "/fictional/public.txt", rules))
        parents = {parent.as_posix() for name in manifest["files"] for parent in Path(name).parents}
        neighbors = {(parent + "/" if parent != "." else "") + "not-admitted-neighbor.txt" for parent in parents}
        neighbors.update({"scripts/tests/private-test.py", "tools/parser-train/unreviewed.json",
                          "packages/vscode/src/private.ts", "docs/research/unreviewed.md"})
        for name in neighbors:
            with self.subTest(excluded=name):
                self.assertFalse(context_admitted(name, rules))
        for name in ("temp/private.txt", "crates/fictional/.airk/state.json", "crates/fictional/target/private.txt",
                     "crates/fictional/.env.local", "crates/fictional/private.pem", "crates/fictional/private.key"):
            with self.subTest(private=name):
                self.assertFalse(context_admitted(name, rules))

    def test_inventory_resolves_each_supported_form_and_the_dynamic_cli_table(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary).resolve()
            source = root / "crates/fictional/src/lib.rs"
            source.parent.mkdir(parents=True)
            source.write_text('''
include_str!("../../../docs/literal.txt",);
include_bytes!("../../../docs/bytes.bin");
include!("../../../tools/native.rs");
include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/", "joined.txt"));
std::fs::read(concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/runtime.txt"));
std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
    .join("../../docs/path.txt",);
''')
            table = root / "crates/airk-cli/tests/cli_commands.rs"
            table.parent.mkdir(parents=True)
            table.write_text('const ELSEWHERE: &[(&str, &str, &str)] = &[\n'
                             '("command", "scripts/check-fictional.py", "assertion"),\n'
                             '("local", "this file", "assertion"),\n];')
            self.assertEqual(external_rust_inputs(root), {
                "docs/literal.txt", "docs/bytes.bin", "tools/native.rs", "docs/joined.txt",
                "docs/runtime.txt", "docs/path.txt", "scripts/check-fictional.py"})
            with source.open("a") as output:
                output.write('Path::new(env!("CARGO_MANIFEST_DIR")).join(dynamic_name);')
            with self.assertRaisesRegex(AssertionError, "explicit inventory"):
                external_rust_inputs(root)

    def test_manifest_matches_source_copy_and_dockerignore_admissions(self):
        manifest = json.loads((ROOT / "scripts/container-inputs.json").read_text())
        expected = set(manifest["files"]) | set(manifest["trees"])
        actual = set()
        source = False
        for opcode, arguments in BUILD.docker_instructions((ROOT / "Dockerfile").read_text()):
            words = shlex.split(arguments)
            if opcode == "FROM":
                if source:
                    break
                source = words[-2:] == ["AS", "source"]
            elif source and opcode == "COPY" and not words[0].startswith("--from="):
                actual.update(words[:-1])
        self.assertEqual(actual, expected)
        ignores = (ROOT / ".dockerignore").read_text().splitlines()
        admitted_files = {line[1:] for line in ignores if line.startswith("!") and not line.endswith(("/", "/**"))}
        admitted_trees = {line[1:-3] for line in ignores if line.startswith("!") and line.endswith("/**")}
        self.assertEqual(admitted_files, set(manifest["files"]))
        self.assertEqual(admitted_trees, set(manifest["trees"]))
        expected_parents = {parent.as_posix() for name in manifest["files"] + manifest["trees"]
                            for parent in Path(name).parents if parent.as_posix() != "."} | set(manifest["trees"])
        admitted_parents = {line[1:-1] for line in ignores if line.startswith("!") and line.endswith("/")}
        self.assertEqual(admitted_parents, expected_parents)
        exclusions = [line for line in ignores if line and not line.startswith(("#", "!"))]
        self.assertEqual(exclusions[0], "**")
        self.assertEqual(exclusions[-6:], ["temp/", "**/.airk/", "**/target/", "**/.env*", "**/*.pem", "**/*.key"])
        self.assertEqual(set(exclusions[1:-6]), {parent + "/**" for parent in expected_parents})

    def test_admin_relative_imports_are_copied_and_covered_by_the_runtime_source_seal(self):
        manifest = json.loads((ROOT / "scripts/container-inputs.json").read_text())
        needed = relative_frontend_inputs(ROOT)
        admitted = set(manifest["files"])
        missing = {name for name in needed if name not in admitted and not any(name.startswith(tree + "/") for tree in manifest["trees"])}
        self.assertEqual(missing, set())
        builder = BUILD.builder
        pathspec = builder.FRONTEND_INPUTS
        unsealed = {name for name in needed if not any(name == source or name.startswith(source + "/") for source in pathspec)}
        self.assertEqual(unsealed, set())
        self.assertIn("packages/vscode/src/uiPilotContract.ts", needed)
        self.assertIn("packages/vscode/src/generated/i2.ts", needed)

    def test_all_external_rust_test_inputs_are_exact_manifest_files(self):
        manifest = json.loads((ROOT / "scripts/container-inputs.json").read_text())
        required = external_rust_inputs(ROOT)
        self.assertGreaterEqual(len(required), 24)
        # A test that reads named files from a fixture folder (U95 parity
        # expectations) is admitted as a manifest tree.
        covered = {name for name in required if any(name == tree or name.startswith(tree + "/") for tree in manifest["trees"])}
        self.assertEqual(required - set(manifest["files"]) - covered, set())
        for name in required:
            if name in manifest["trees"]:
                self.assertTrue((ROOT / name).is_dir(), name)
            else:
                self.assertTrue((ROOT / name).is_file(), name)


if __name__ == "__main__":
    unittest.main()
