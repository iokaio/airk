"""Inventory literal Rust ignores and nextest profile exclusions; never run tests."""
import argparse
from datetime import datetime, timezone
from pathlib import Path
import re
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]
IGNORE = re.compile(r'^\s*#\[ignore(?:\s*=\s*"([^"\n]*)")?\]\s*$', re.MULTILINE)
FUNCTION = re.compile(r"\b(?:async\s+)?fn\s+([A-Za-z0-9_]+)\s*\(")


def inventory(root=ROOT):
    rows = []
    for path in sorted((root / "crates").rglob("*.rs")):
        text = path.read_text(encoding="utf-8")
        for match in IGNORE.finditer(text):
            function = FUNCTION.search(text, match.end())
            if not function:
                raise ValueError(f"Cannot identify ignored test after {path}")
            reason = match[1] or "missing reason; triage required"
            category = "helper" if any(part in reason for part in ["subprocess", "invoked only", "child-process crash fixture"]) else "qualification"
            if match[1] is None:
                category = "debt"
            rows.append({"path": path.relative_to(root).as_posix(),
                         "line": text.count("\n", 0, match.start()) + 1,
                         "name": function[1], "reason": reason, "category": category})
    profile = tomllib.loads((root / ".config/nextest.toml").read_text(encoding="utf-8"))["profile"]["ci"]
    exclusions = re.findall(r"test\(([^)]+)\)", profile["default-filter"])
    return rows, exclusions


def render(rows, exclusions, revision, date):
    helpers = sum(row["category"] == "helper" for row in rows)
    debt = sum(row["category"] == "debt" for row in rows)
    lines = ["# Ignored-test and profile-exclusion inventory", "",
             f"**Observed:** {date} UTC. **Entry revision:** `{revision}` (working source inventory).",
             "Generated by `python scripts/report-test-skips.py --write`; recheck live source before using this snapshot.", "",
             f"The snapshot contains **{len(rows)} literal Rust ignore attributes**: **{helpers} helper entry points**,",
             f"**{len(rows) - helpers - debt} explicit qualification cases**, **{debt} missing-reason debt entries**.",
             "This classification is not a passing test result or an assertion that qualified cases have no debt.",
             f"The separate nextest CI filter excludes **{len(exclusions)}** long workload/measurement cases below.", "",
             "## Commands and qualification boundaries", "",
             "Ordinary `cargo nextest run --workspace --all-features --locked --profile ci` preserves ignores and the default exclusions.",
             "`--ignore-default-filter` restores those excluded cases; it does not enable ignored tests.",
             "For a qualification row, first satisfy its stated fixture/model/platform requirement, then run the owning target with",
             "`cargo test -p <crate> --all-features --test <integration-file-stem> <test-name> -- --ignored --nocapture`",
             "or `--lib` for an inline/source test. Timing cases require their documented release profile and uncontended host.",
             "Never run helper entries standalone; their parent tests own invocation, environment, process containment and assertions.",
             "Native sealed-pair installer tests require explicitly approved current payload hashes; predecessor tests require retained images.",
             "Use an already private supported `AIRK_PRIVATE_CENSUS_BASE` when required; never change a user's ACL or grant privilege to obtain a pass.",
             "Do not automatically install a runtime, create an account, provision a share or change OS ownership for this inventory.", "",
             "## Rust ignore attributes", "",
             "| Category | Source / test name | Current reason |", "| --- | --- | --- |"]
    for row in rows:
        source = row["path"]
        reason = row["reason"].replace("|", "\\|")
        lines.append(f"| {row['category']} | [{source}](../../{source}) · `{row['name']}` | {reason} |")
    lines += ["", "## Nextest CI default exclusions", "",
              "These are not ignored attributes. Each is restored by `--ignore-default-filter` under the same CI profile.", ""]
    lines += [f"- `{name}`" for name in exclusions]
    lines += ["", "## Runtime/platform skips and remaining evidence", "",
              "Rust `cfg` gates, nextest profile exclusions and ignored attributes are different populations; do not equate this source count with a runner's skipped count.",
              "Extension tests additionally skip by platform, `AIRK_TEST_BINARY`, `AIRK_EDITOR_RUN` and explicitly enabled installed fixtures; Python suites also have conditional platform/tool skips.",
              "Record actual runner pass/fail/skip totals, target/features, supplied environment, exact payload and skipped case IDs for each qualification run.",
              "P5's dated Windows result was 1,939 native passed / 37 skipped, 547 extension passed / 19 skipped, and 309 Python cases / six skipped; these totals are historical evidence, not expected counts for future phases.",
              "P5 separately ran its explicitly gated staged installer and retained-predecessor campaigns; the ordinary skip total does not imply those separate campaigns were omitted.",
              "Second-account privacy, real signed macOS copied-launcher/editor paths, SMB/privileged path fixtures and other-platform results remain separately qualified.",
              "Any newly discovered real debt needs a concrete blocker and remediation in the phase ledger; this snapshot creates no external issues and weakens no existing gate.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Write docs/testing/ignore-triage.md instead of stdout")
    args = parser.parse_args()
    revision = subprocess.check_output(["git", "-c", f"safe.directory={ROOT.as_posix()}", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    rows, exclusions = inventory()
    content = render(rows, exclusions, revision, datetime.now(timezone.utc).date().isoformat())
    if args.write:
        destination = ROOT / "docs/testing/ignore-triage.md"
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")
        print(f"Wrote {len(rows)} Rust ignores and {len(exclusions)} profile exclusions to {destination}")
    else:
        print(content)


if __name__ == "__main__":
    main()
