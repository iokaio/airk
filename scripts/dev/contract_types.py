"""Render TypeScript types from a checked-in contract JSON Schema (split plan U47).

The Rust owner emits the schema (for I2: `cargo test -p airkctl --lib
contract_schema` pins `packages/vscode/src/generated/i2.schema.json`; for I3:
`cargo test -p airk-cli --lib admin_contract` pins
`packages/contracts-gen/i3.schema.json`). This renderer turns a schema into the
`.ts` file beside it. It supports only the constructs the contracts use and
fails on anything else, so it never guesses a type.

    python scripts/dev/contract_types.py i2 --check   # exit 1 on drift
    python scripts/dev/contract_types.py i3 --write

Known limits recorded by the pilot: 64-bit integers render as `number` and
are only exact up to 2**53 - 1; the contract keeps such fields bounded.
"""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
CONTRACTS = {
    "arbiter": ROOT / "packages/contracts-gen/arbiter.schema.json",
    "i2": ROOT / "packages/vscode/src/generated/i2.schema.json",
    "i3": ROOT / "packages/contracts-gen/i3.schema.json",
}
HEADER = ("// SPDX-License-Identifier: Apache-2.0\n"
          "// Generated by scripts/dev/contract_types.py from {schema}. Do not edit.\n"
          "// Owner: {title} (Rust). Semantic rules stay hand-written and fixture-tested.\n")
KNOWN = {"$ref", "type", "properties", "required", "additionalProperties", "description",
         "format", "minimum", "maximum", "enum", "const", "oneOf", "anyOf", "items", "pattern", "uniqueItems",
         "minItems", "maxItems"}
IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


class Unsupported(ValueError):
    pass


def comment(text, indent):
    lines = text.strip().splitlines()
    if not lines:
        return ""
    body = "\n".join(f"{indent} * {line}".rstrip() for line in lines)
    return f"{indent}/**\n{body}\n{indent} */\n"


def scalar(kind, schema):
    if kind == "string":
        return json.dumps(schema["const"]) if "const" in schema else "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    raise Unsupported(f"type {kind!r}")


def render(schema, indent=""):
    if schema is True or schema == {} or set(schema) <= {"description"}:
        return "unknown"
    unknown = set(schema) - KNOWN
    if unknown:
        raise Unsupported(f"keywords {sorted(unknown)}")
    if "$ref" in schema:
        name = schema["$ref"].removeprefix("#/$defs/")
        if not IDENTIFIER.fullmatch(name) or name == schema["$ref"]:
            raise Unsupported(f"reference {schema['$ref']!r}")
        return name
    for key in ("oneOf", "anyOf"):
        if key in schema:
            return " | ".join(render(item, indent) for item in schema[key])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(render({**schema, "type": item}, indent) for item in kind)
    if kind == "array":
        item = render(schema["items"], indent)
        return f"Array<{item}>"
    if kind == "object":
        return object_type(schema, indent)
    if kind is None and "const" in schema:
        return json.dumps(schema["const"])
    return scalar(kind, schema)


def object_type(schema, indent):
    if schema.get("additionalProperties") not in (False, None):
        # Native BTreeMap<String, Value> is a pure JSON map. Do not broaden a
        # mixed named object into an index signature that conceals its contract.
        if schema.get("additionalProperties") is True and not schema.get("properties") and not schema.get("required"):
            return "Record<string, unknown>"
        raise Unsupported("open mixed or typed object")
    required = set(schema.get("required", []))
    inner = indent + "    "
    lines = ["{"]
    for name, member in schema.get("properties", {}).items():
        property_name = name if IDENTIFIER.fullmatch(name) else json.dumps(name)
        if isinstance(member, dict) and member.get("description"):
            lines.append(comment(member["description"], inner).rstrip("\n"))
        optional = "" if name in required else "?"
        lines.append(f"{inner}{property_name}{optional}: {render(member, inner)};")
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def generate(contract):
    path = CONTRACTS[contract]
    document = json.loads(path.read_text(encoding="utf-8"))
    output = [HEADER.format(schema=path.relative_to(ROOT).as_posix(), title=document["title"])]
    output.append(f"export const {contract.upper()}_CONTRACT = {int(document[contract + '_contract'])};\n")
    for name, schema in sorted(document["$defs"].items()):
        if not IDENTIFIER.fullmatch(name):
            raise Unsupported(f"definition {name!r}")
        output.append("\n" + comment(schema.get("description", ""), ""))
        output.append(f"export type {name} = {render(schema)};\n")
    return "".join(output)


def declaration_only(source, contract):
    """Accept only this generator's literal constant and type-expression grammar."""
    tokens = []
    pattern = re.compile(r'\s+|//[^\n]*|/\*[\s\S]*?\*/|"(?:[^"\\]|\\.)*"|'
                         r'[A-Za-z_][A-Za-z0-9_]*|-?[0-9]+(?:\.[0-9]+)?|[{}<>,?:;=|]')
    offset = 0
    while offset < len(source):
        match = pattern.match(source, offset)
        if match is None:
            raise Unsupported("non-declaration TypeScript token")
        token = match.group()
        offset = match.end()
        if not token.isspace() and not token.startswith(("//", "/*")):
            tokens.append(token)
    position = 0

    def take(expected=None):
        nonlocal position
        if position == len(tokens) or expected is not None and tokens[position] != expected:
            raise Unsupported("non-declaration TypeScript statement")
        value = tokens[position]
        position += 1
        return value

    def type_expression():
        atom()
        while position < len(tokens) and tokens[position] == "|":
            take("|")
            atom()

    def atom():
        value = take()
        if value == "{":
            while position < len(tokens) and tokens[position] != "}":
                member = take()
                if not IDENTIFIER.fullmatch(member) and not quoted(member):
                    raise Unsupported("non-declaration object member")
                if position < len(tokens) and tokens[position] == "?":
                    take("?")
                take(":")
                type_expression()
                take(";")
            take("}")
        elif value == "Array":
            take("<")
            type_expression()
            take(">")
        elif value == "Record":
            take("<")
            take("string")
            take(",")
            type_expression()
            take(">")
        elif not (IDENTIFIER.fullmatch(value) or quoted(value)
                  or re.fullmatch(r'-?[0-9]+(?:\.[0-9]+)?', value)):
            raise Unsupported("non-declaration type expression")

    def quoted(value):
        if not value.startswith('"'):
            return False
        try:
            return isinstance(json.loads(value), str)
        except ValueError as error:
            raise Unsupported("invalid quoted type literal") from error

    take("export")
    take("const")
    take(contract.upper() + "_CONTRACT")
    take("=")
    if not re.fullmatch(r"[0-9]+", take()):
        raise Unsupported("nonliteral contract version")
    take(";")
    while position < len(tokens):
        take("export")
        take("type")
        if not IDENTIFIER.fullmatch(take()):
            raise Unsupported("non-declaration type name")
        take("=")
        type_expression()
        take(";")


def declaration_target(contract):
    # The editor's src-only rootDir consumes the same native types without
    # compiling another runtime module or maintaining a second DTO definition.
    return ROOT / f"packages/vscode/src/generated/{contract}.d.ts" if contract in {"i3", "arbiter"} else None


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("contract", choices=sorted(CONTRACTS))
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    target = CONTRACTS[args.contract].with_suffix("").with_suffix(".ts")
    rendered = generate(args.contract)
    alias = declaration_target(args.contract)
    if alias is not None:
        declaration_only(rendered, args.contract)
    if args.write:
        target.write_text(rendered, encoding="utf-8", newline="\n")
        if alias is not None:
            alias.parent.mkdir(parents=True, exist_ok=True)
            alias.write_bytes(target.read_bytes())
        return 0
    current = target.read_text(encoding="utf-8").replace("\r\n", "\n") if target.exists() else ""
    if current != rendered:
        print(f"{target.relative_to(ROOT).as_posix()} differs from its schema; run --write after review",
              file=sys.stderr)
        return 1
    if alias is not None:
        declaration_only(target.read_text(encoding="utf-8"), args.contract)
        if not alias.exists() or alias.read_bytes() != target.read_bytes():
            print(f"{alias.relative_to(ROOT).as_posix()} differs from canonical types; run --write after review",
                  file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
